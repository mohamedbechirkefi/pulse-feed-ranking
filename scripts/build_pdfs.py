"""Build the manuscript, supplementary and experiment-report PDFs (M6), and manuscript.tex.

Markdown is canonical. pandoc converts each file to Typst (the first level-1 heading becomes the
document title, so the PDF title metadata is set, and the other headings move up one level), the typst Python package compiles it, and the
intermediate .typ file is removed unless --keep-typ is given. With --png DIR every page is also
rendered to PNG in DIR for visual inspection. manuscript.tex is generated by pandoc (LaTeX writer);
no TeX distribution is needed to generate it.

    PYTHONPATH=src .venv/bin/python scripts/build_pdfs.py [--png DIR] [--keep-typ]
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pulse.report import PANDOC, TYPST_PY  # noqa: E402

DOCS = [
    ("ms", ROOT / "research/paper/manuscript.md"),
    ("supp", ROOT / "research/paper/supplementary.md"),
    *[(f"exp{n}", ROOT / f"research/experiments/EXP-00{n}/report.md") for n in (1, 2, 3, 4)],
]
# --columns=1000 keeps pipe tables "short" for pandoc, so Typst sizes columns to their content
# instead of giving every column the same width; table cells are set ragged-right and slightly smaller.
TABLE_STYLE = ("#show table: set par(justify: false)\n#show table: set text(size: 8pt)\n"
               # long hashes may break at any character instead of running into the next column
               "#show regex(\"[0-9a-f]{20,}\"): it => it.text.clusters().join(sym.zws)")
PANDOC_TYPST = ["-s", "-t", "typst", "--shift-heading-level-by=-1", "--columns=1000",
                "-V", "mainfont=Libertinus Serif", "-V", "fontsize=9pt", "-V", "papersize=a4",
                "-V", f"header-includes={TABLE_STYLE}"]

COMPILE = """
import sys, typst
typ, pdf, root, png = sys.argv[1:5]
typst.compile(typ, output=pdf, root=root)
if png:
    typst.compile(typ, output=png, format="png", ppi=60, root=root)
"""


def split_title(md: Path) -> tuple[str, str]:
    """Return (title, body): the first level-1 heading becomes metadata and is removed from the body."""
    lines = md.read_text(encoding="utf-8").splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith("# "):
            return line[2:].strip(), "".join(lines[:i] + lines[i + 1:])
    raise ValueError(f"no level-1 heading in {md}")


def pandoc(md: Path, args: list[str], out: str) -> None:
    title, body = split_title(md)
    subprocess.run([str(PANDOC), "-f", "markdown", *args, "-M", f"title={title}", "-o", out],
                   input=body, text=True, cwd=md.parent, check=True)


def build(tag: str, md: Path, png_dir: Path | None, keep_typ: bool) -> Path:
    typ = md.with_suffix(".typ")
    pandoc(md, PANDOC_TYPST, typ.name)
    pdf = md.with_suffix(".pdf")
    png = str(png_dir / f"{tag}-{{p}}.png") if png_dir else ""
    subprocess.run([str(TYPST_PY), "-I", "-c", COMPILE, str(typ), str(pdf), str(md.parent), png], check=True)
    if not keep_typ:
        typ.unlink()
    return pdf


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--png", type=Path, default=None, help="render every page to PNG in this directory")
    ap.add_argument("--keep-typ", action="store_true")
    a = ap.parse_args(argv)
    if not PANDOC.exists() or not TYPST_PY.exists():
        print(f"missing toolchain: {PANDOC} or {TYPST_PY}", file=sys.stderr)
        return 2
    if a.png:
        a.png.mkdir(parents=True, exist_ok=True)
    for tag, md in DOCS:
        pdf = build(tag, md, a.png, a.keep_typ)
        print(f"{pdf.relative_to(ROOT)} {pdf.stat().st_size} bytes")
    ms = ROOT / "research/paper/manuscript.md"
    pandoc(ms, ["-s", "-t", "latex", "--shift-heading-level-by=-1"], "manuscript.tex")
    tex = ms.with_suffix(".tex")
    tex.write_text("% SPDX-License-Identifier: LicenseRef-PULSE-NC-Research-1.0\n% Generated from manuscript.md by scripts/build_pdfs.py; do not edit.\n"
                   + tex.read_text(encoding="utf-8"), encoding="utf-8")
    print("research/paper/manuscript.tex written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
