"""Markdown tables for an experiment report, generated from the analysis outputs (never typed by hand).

Usage: PYTHONPATH=src .venv/bin/python scripts/report_tables.py EXP-00N > research/experiments/EXP-00N/tables.md

Reads research/experiments/EXP-00N/{summary.csv, contrasts.csv, verdict.json}. Presentation only:
every number comes from those files, which scripts/analyse_experiment.py derives from raw results.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

from pulse.manifest import REPO_ROOT

METRIC_NAMES = {"h_exp": "H_exp", "gini_exposure": "Gini", "relevance": "relevance",
                "miscalibration_kl": "miscal. KL", "user_control": "user control", "like_rate": "like rate",
                "delta_h_pref": "Delta H_pref"}


def f(v, nd=4) -> str:
    if v in (None, ""):
        return "NA"
    return f"{float(v):.{nd}f}"


def p(v) -> str:
    if v in (None, ""):
        return "NA"
    v = float(v)
    return "<0.0001" if v < 1e-4 else f"{v:.4f}"


def table(head: list[str], rows: list[list[str]]) -> str:
    out = "| " + " | ".join(head) + " |\n| " + " | ".join("---" for _ in head) + " |\n"
    return out + "".join("| " + " | ".join(r) + " |\n" for r in rows)


def main(exp: str) -> int:
    d = REPO_ROOT / "research" / "experiments" / exp
    summary = list(csv.DictReader((d / "summary.csv").open(encoding="utf-8")))
    contr = list(csv.DictReader((d / "contrasts.csv").open(encoding="utf-8")))
    v = json.loads((d / "verdict.json").read_text(encoding="utf-8"))
    metrics = [m for m in METRIC_NAMES if any(r.get(f"{m}_mean") not in ("", None) for r in summary)]
    print(f"<!-- generated by scripts/report_tables.py {exp} from summary.csv, contrasts.csv, verdict.json -->\n")
    print("### Table A. Per-arm means (SD over seeds)\n")
    rows = [[r["cell"], r["arm"], f"{r['n_ok']}/{r['n_runs']}"] +
            [f"{f(r[m + '_mean'])} ({f(r[m + '_sd'])})" for m in metrics] for r in summary]
    print(table(["cell", "arm", "ok/runs"] + [METRIC_NAMES[m] for m in metrics], rows))
    print("### Table B. Paired contrasts, all metrics (treatment minus control; 95% t and bootstrap intervals; "
          "Holm within cell and metric family)\n")
    rows = [[c["cell"], METRIC_NAMES[c["metric"]], f"{c['treatment']} - {c['control']}", c["n"], f(c["mean_diff"]),
             f"[{f(c['t_lo'])}, {f(c['t_hi'])}]", f"[{f(c['boot_lo'])}, {f(c['boot_hi'])}]", f(c["d_z"], 2),
             p(c["p_two_sided"]), p(c["p_holm"])] for c in contr]
    print(table(["cell", "metric", "contrast", "n", "mean", "95% t CI", "95% boot CI", "d_z", "p", "p Holm"], rows))
    print("### Table C. Frozen decision rule\n")
    prim = [v["primary"]] + v.get("secondary_cells", []) + v.get("cells", [])
    seen, rows = set(), []
    for c in prim:
        key = (c["block"], json.dumps(c["cell"], sort_keys=True))
        if key in seen:
            continue
        seen.add(key)
        cell = ",".join(f"{k}={val}" for k, val in c["cell"].items()) or "base"
        rows.append([f"{c['block']}:{cell}", METRIC_NAMES[c["metric"]], f"{c['treatment']} - {c['control']}",
                     f(c["mean_diff"]), f"[{f(c['t_lo'])}, {f(c['t_hi'])}]", f(c["d_z"], 2),
                     "yes" if c["h1_supported"] else "no", c["reason"]])
    print(table(["cell", "metric", "contrast", "mean", "95% t CI", "d_z", "H1 supported", "rule outcome"], rows))
    if "skew_interaction" in v:
        print("### Table D. Skew interaction (Welch)\n")
        print(table(["block", "contrast", "diff", "95% Welch CI", "df"],
                    [[i["block"], i["contrast"], f(i["diff"]), f"[{f(i['lo'])}, {f(i['hi'])}]", f(i["df"], 1)]
                     for i in v["skew_interaction"]]))
        print(f"Skew criterion met: {v['skew_criterion_met']}; sharpness criterion met: "
              f"{v['sharpness_criterion_met']}.\n")
    if "drift_form" in v:
        print("### Table D. Drift-form check (gamma = 0.05)\n")
        print(table(["alpha_0", "D multiplicative", "D additive-clip", "95% t CI (additive-clip)", "sign change",
                     "|D| < 0.05", "dependent on drift form"],
                    [[str(x["alpha0"]), f(x["D_multiplicative"]), f(x["D_additive_clip"]),
                      f"[{f(x['check']['t_lo'])}, {f(x['check']['t_hi'])}]", str(x["sign_change"]),
                      str(x["abs_below_sesoi"]), str(x["dependent_on_drift_form"])] for x in v["drift_form"]]))
    print("### Table E. Run diagnostics (mean over seeds; from the raw result files)\n")
    from collections import defaultdict

    from pulse.schema import load_results
    g = defaultdict(list)
    for r in load_results(REPO_ROOT / "results" / "raw" / exp):
        cell = ",".join(f"{k}={val}" for k, val in r["cell"].items()) or "base"
        g[(f"{r['block']}:{cell}", r["arm"])].append(r["diagnostics"])
    keys = ("catalog_topic_entropy", "pool_topic_entropy_window", "distinct_items_exposed_window",
            "n_dislike_events")
    print(table(["cell", "arm"] + list(keys),
                [[c, a] + [f(sum(d[k] for d in ds) / len(ds), 4 if "entropy" in k else 1) for k in keys]
                 for (c, a), ds in sorted(g.items())]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
